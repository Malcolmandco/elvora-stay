export function getHotelbedsCode(elvoraName: string): string | null {
  const name = elvoraName.toLowerCase();
  const entry = hotelbedsDestinationMap.find(
    (m) => m.elvoraName.toLowerCase() === name
  );
  if (entry) return entry.hotelbedsCode;
  // Try partial match: "New York City" matches "New York"
  const partial = hotelbedsDestinationMap.find(
    (m) => name.startsWith(m.elvoraName.toLowerCase()) || m.elvoraName.toLowerCase().startsWith(name)
  );
  return partial ? partial.hotelbedsCode : null;
}

export function getElvoraNameFromHotelbedsCode(code: string): string | null {
  const entry = hotelbedsDestinationMap.find(
    (m) => m.hotelbedsCode === code.toUpperCase()
  );
  return entry ? entry.elvoraName : null;
}
